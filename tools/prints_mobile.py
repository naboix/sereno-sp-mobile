"""Gera prints REAIS do app Sereno SP (build web exportada) via Chrome headless.
Ambiente: servidor de contrato SIMULADO em :5128 (as telas exibem a faixa 'SIMULADOS')."""
import subprocess, time, sys, os, urllib.request
from playwright.sync_api import sync_playwright
APP='http://127.0.0.1:8090'
OUT=sys.argv[1]; MOBILE=sys.argv[2]
os.makedirs(OUT, exist_ok=True)
def mock(cenario):
    return subprocess.Popen(['node','--disable-warning=MODULE_TYPELESS_PACKAGE_JSON','mock-server/server.ts'],cwd=MOBILE,env={**os.environ,'PORTA':'5128','CENARIO':cenario},stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
def cen(nome):
    urllib.request.urlopen(urllib.request.Request(f'http://127.0.0.1:5128/__demo/cenario?nome={nome}',method='POST')).read()
def shot(page,nome,full=False):
    time.sleep(1.2); page.screenshot(path=f'{OUT}/{nome}.png',full_page=full); print('print',nome)
srv=mock('perigo'); time.sleep(1.5)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':412,'height':915},device_scale_factor=2,locale='pt-BR',timezone_id='America/Sao_Paulo')
    page=ctx.new_page()
    erros=[]; page.on('pageerror',lambda e: erros.append(str(e)))
    page.goto(APP); page.wait_for_selector('text=Começar',timeout=30000)
    shot(page,'01-onboarding-boas-vindas')
    page.get_by_test_id('botao-comecar').click(); page.wait_for_selector('text=Seu perfil')
    page.get_by_test_id('botao-concluir').click(); time.sleep(0.5)
    shot(page,'02-onboarding-validacao')
    page.get_by_test_id('campo-apelido').fill('Dona Lúcia')
    page.get_by_role('radio',name='70 a 79 anos').click()
    page.get_by_role('button',name='Moro em Santana').click()
    page.get_by_test_id('interruptor-consentimento').click()
    shot(page,'03-onboarding-preenchido')
    page.get_by_test_id('botao-concluir').click()
    page.wait_for_selector('text=Calor agora',timeout=20000)
    shot(page,'04-inicio-perigo')
    page.mouse.move(206,500); page.mouse.wheel(0,1500); shot(page,'04b-inicio-previsao-amanha')
    page.mouse.wheel(0,1500); shot(page,'04c-inicio-bebi-agua')
    page.get_by_test_id('botao-bebi-agua').click(); page.wait_for_selector('[data-testid=confirmacao]')
    page.get_by_test_id('cartao-agua').scroll_into_view_if_needed()
    shot(page,'05-inicio-bebi-agua-confirmado',full=False)
    page.get_by_test_id('aba-pontos').click(); page.wait_for_selector('text=Mais próximos'); page.wait_for_selector('text=Ver detalhes',timeout=15000)
    shot(page,'06-pontos-refresco')
    page.mouse.move(206,500); page.mouse.wheel(0,1300); shot(page,'06b-pontos-lista-proximos')
    page.mouse.wheel(0,-3000)
    page.get_by_role('button',name='Salvar Ponto Demo A - Praça com sombra (fictício) nos favoritos').first.click(); time.sleep(1)
    page.get_by_role('button',name='Ver detalhes').first.click(); page.wait_for_selector('text=Horário de funcionamento')
    shot(page,'07-detalhe-ponto')
    page.go_back(); page.wait_for_selector('text=Mais próximos')
    page.get_by_test_id('aba-alertas').click(); page.wait_for_selector('text=Alertas de calor'); time.sleep(1); page.mouse.move(206,500); page.mouse.wheel(0,250)
    shot(page,'08-alertas-vigentes')
    page.get_by_role('radio',name='Histórico neste celular').click()
    shot(page,'09-alertas-historico')
    page.get_by_test_id('aba-perfil').click(); page.wait_for_selector('text=Perfil e preferências')
    page.get_by_role('button',name='Testar conexão').click(); time.sleep(1.5)
    shot(page,'10-perfil-preferencias')
    page.get_by_test_id('pref-fonte').get_by_role('radio',name='Muito grande').click()
    page.get_by_test_id('pref-contraste').click()
    page.get_by_test_id('aba-inicio').click(); page.wait_for_selector('text=Calor agora')
    shot(page,'11-inicio-fonte-muito-grande-contraste')
    page.get_by_test_id('aba-perfil').click(); page.get_by_test_id('pref-fonte').get_by_role('radio',name='Grande',exact=True).click(); page.get_by_test_id('pref-contraste').click()
    # leitura antiga e sem previsao
    cen('antiga'); page.goto(APP+'/inicio'); page.wait_for_selector('text=Calor agora'); page.wait_for_selector('[data-testid=aviso-leitura-antiga]',timeout=15000)
    page.get_by_test_id('aviso-leitura-antiga').scroll_into_view_if_needed(); shot(page,'12-inicio-leitura-antiga')
    cen('sem-previsao'); page.goto(APP+'/inicio'); page.wait_for_selector('text=Previsão indisponível',timeout=15000)
    page.get_by_test_id('cartao-amanha').scroll_into_view_if_needed()
    shot(page,'13-inicio-previsao-indisponivel',full=False)
    cen('perigo'); page.goto(APP+'/inicio'); page.wait_for_selector('[data-testid=faixa-origem-simulado]',timeout=15000)
    # offline: desliga o servidor
    srv.terminate(); srv.wait(); page.goto(APP+'/inicio'); page.wait_for_selector('[data-testid=faixa-origem-cache]',timeout=30000)
    shot(page,'14-inicio-sem-conexao-cache')
    page.get_by_test_id('aba-pontos').click(); page.wait_for_selector('text=Meus favoritos'); time.sleep(3)
    page.mouse.move(206,500); page.mouse.wheel(0,1500); shot(page,'15-pontos-sem-conexao-favoritos')
    print('erros de pagina:',erros)
    b.close()
